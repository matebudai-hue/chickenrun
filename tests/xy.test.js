import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { memoryStore } from "../local.mjs";
import { points, multipliers, xyApi } from "../worker/xy.js";

test("paper payouts at every supported stake", () => {
  for (const m of multipliers) {
    assert.deepEqual([1,2,3,4].map(x=>points("X",x,m)),[30,20,10,-10].map(x=>x*m));
    assert.deepEqual([0,1,2,3].map(x=>points("Y",x,m)),[10,-10,-20,-30].map(x=>x*m));
  }
});

test("four teams, negotiations, concurrent moves, recovery, projection and reflections", async () => {
  const store=memoryStore();
  const originalSeen=store.seen;
  const originalPulse=store.pulse;
  const stale=new Set();
  store.seen=code=>new Map([...originalSeen(code)].map(([key,time])=>[key,stale.has(key)?time-26000:time]));
  store.pulse=async(code,key)=>{await originalPulse(code,key);stale.delete(key);};
  const [host,projector,a,b,c,d,replacement,invite,outsider]=Array.from({length:9},(_,i)=>String(i+1).repeat(32));
  const code="ABC234";
  const teams=[a,b,c,d];
  const ownerKey="f".repeat(32);
  const ownerDigest=createHash("sha256").update(ownerKey).digest("hex");
  const activity=key=>xyApi(new Request("https://example.test/api/xy/activity",{headers:{authorization:"Bearer "+key}}),store,ownerDigest);
  const call=async(act,key,body,status=200)=>{
    const path=act==="create"?"/api/xy/rooms":"/api/xy/rooms/"+code+(act==="idle"?"?idle=1":act?"/"+act:"");
    const response=await xyApi(new Request("https://example.test"+path,{
      method:act&&act!=="idle"&&act!=="report"?"POST":"GET",headers:key?{authorization:"Bearer "+key}:{},body:act&&act!=="idle"&&act!=="report"?JSON.stringify(body||{}):undefined
    }),store,ownerDigest);
    const data=await response.json();
    assert.equal(response.status,status,JSON.stringify(data));
    return data;
  };
  await call("create",null,{code,key:host,projector,rounds:10},201);
  await call("create",null,{code,key:host,projector,rounds:10});
  await call("start",host,{},409);
  await Promise.all(teams.map((key,i)=>call("join",key,{name:"Team "+(i+1)})));
  assert.deepEqual((await call("",host)).presence,Array(4).fill("online"));
  for(const key of originalSeen("xy:"+code).keys()) stale.add(key);
  assert.deepEqual((await call("",host)).presence,Array(4).fill("offline"));
  await call("idle",a);
  assert.equal((await call("",host)).presence[0],"offline");
  await call("",a);
  assert.equal((await call("",host)).presence[0],"online");
  assert.equal((await call("",a)).presence,undefined);
  await call("join",outsider,{name:"Fifth"},409);
  await call("config",host,{index:0,multiplier:1000,negotiations:2});
  assert.equal((await call("",a)).rounds[0].multiplier,undefined);
  assert.equal((await call("",projector)).rounds[0].multiplier,undefined);
  await call("start",host,{});
  await call("open",host,{index:0},409);
  for(let i=0;i<2;i++){
    await call("negotiation",host,{index:0});
    assert.equal((await call("",a)).phase,"negotiation");
    assert.equal((await call("",a)).rounds[0].multiplier,undefined);
    await call("resume",host,{index:0});
  }
  await call("open",host,{index:0});
  assert.equal((await call("",a)).rounds[0].multiplier,1000);
  assert.equal((await call("",a)).rounds[1].multiplier,undefined);
  await call("config",host,{index:0,multiplier:5,negotiations:2},409);
  await call("close",host,{index:0},409);
  await call("screen",host,{mode:"matrix"});
  assert.equal((await call("",projector)).mode,"matrix");
  await call("close",projector,{index:0},403);
  await call("note",a,{index:0,text:"Túl korán"},409);
  await Promise.all(teams.map((key,i)=>call("move",key,{index:0,choice:i===0?"X":"Y"})));
  assert.equal((await call("note",a,{index:0,text:"Első kör"})).rounds[0].note,"Első kör");
  const liveNote=await call("",host);
  assert.deepEqual(liveNote.rounds[0].noteFlags,[true,false,false,false]);
  assert.equal(liveNote.rounds[0].hostNotes[0],"Első kör");
  assert.equal((await call("",projector)).rounds[0].hostNotes,undefined);
  assert.equal((await call("",b)).rounds[0].hostNotes,undefined);
  assert.equal((await call("move",a,{index:0,choice:"Y"})).rounds[0].own,"Y");
  assert.equal((await call("",a)).rounds[0].note,"Első kör");
  assert.equal((await call("",b)).rounds[0].note,"");
  assert.equal((await call("",host)).rounds[0].moves[0],"Y");
  await call("move",a,{index:0,choice:"X"});
  assert.deepEqual((await call("",host)).rounds[0].moves,["X","Y","Y","Y"]);
  assert.equal((await call("",projector)).rounds[0].moves,undefined);
  assert.equal((await call("",b)).rounds[0].moves,undefined);
  const close=await call("close",host,{index:0});
  assert.deepEqual(close.totals,[30000,-10000,-10000,-10000]);
  assert.equal((await call("",projector)).rounds[0].countX,undefined);
  assert.equal((await call("",projector)).rounds[0].multiplier,1000);
  assert.equal((await call("",projector)).rounds[0].projectorNotes,undefined);
  await call("move",a,{index:0,choice:"Y"},409);
  await call("close",host,{index:0});
  await call("transfer",host,{seat:0,transfer:invite});
  assert.equal((await call("join",replacement,{transfer:invite})).ownTotal,30000);
  await call("",a,undefined,403);
  await call("join",outsider,{transfer:invite},409);
  await call("next",host,{index:0});
  await call("open",host,{index:1});
  await call("move",replacement,{index:0,choice:"Y"},409);
  await call("manual",host,{index:1,seat:0,choice:"Y"});
  await Promise.all([b,c,d].map(key=>call("move",key,{index:1,choice:"Y"})));
  await call("close",host,{index:1});
  await call("next",host,{index:1});
  await call("negotiation",host,{index:2});
  await call("resume",host,{index:2});
  await call("open",host,{index:2});
  await call("move",replacement,{index:2,choice:"X"});
  const early=await call("finish",host,{index:2});
  assert.equal(early.phase,"finished");
  assert.deepEqual(early.totals,[30010,-9990,-9990,-9990]);
  assert.deepEqual(early.rounds[2].moves,[null,null,null,null]);
  assert.deepEqual((await call("",projector)).rounds[0].noteFlags,[true,false,false,false]);
  assert.equal((await call("",projector)).rounds[0].projectorNotes[0],"Első kör");
  assert.equal((await call("",b)).rounds[0].projectorNotes,undefined);
  assert.equal((await call("",b)).rounds[0].noteFlags,undefined);
  assert.equal((await call("",projector)).projectedNote,undefined);
  await call("screen",host,{mode:"note",round:0,seat:0,anonymous:true});
  assert.deepEqual((await call("",projector)).projectedNote,{text:"Első kör",round:0,name:""});
  assert.equal((await call("",b)).projectedNote,undefined);
  await call("focus",host,{index:null});
  assert.equal((await call("",projector)).mode,"live");
  await call("reflection",replacement,{text:"Az első tárgyalás után változott."});
  assert.equal((await call("",host)).reflections[0],"Az első tárgyalás után változott.");
  assert.equal((await call("",b)).reflections,undefined);
  assert.equal((await call("",projector)).projectorReflections[0],"Az első tárgyalás után változott.");
  assert.equal((await call("",b)).projectorReflections,undefined);
  await call("screen",host,{mode:"reflection",seat:0,anonymous:true});
  const projected=await call("",projector);
  assert.deepEqual(projected.projectedReflection,{name:"",text:"Az első tárgyalás után változott."});
  assert.equal((await call("",b)).rounds[0].moves,undefined);
  const teamView=await call("",b);
  assert.equal(teamView.names,undefined);
  assert.equal(teamView.totals,undefined);
  assert.equal(teamView.rounds[0].moves,undefined);
  assert.equal(teamView.rounds[0].scores,undefined);
  await call("report",b,undefined,403);
  const hostReport=await call("report",host);
  assert.equal(hostReport.rounds[0].notes[0],"Első kör");
  assert.equal(hostReport.rounds[2].negotiations,1);
  assert.equal(hostReport.rounds[2].scores,null);
  await call("reportshare",b,{enabled:true},403);
  await call("reportshare",host,{enabled:true});
  assert.equal((await call("",b)).reportShared,true);
  const report=await call("report",b);
  assert.equal(report.rounds[0].notes[0],"Első kör");
  assert.equal(report.reflections[0],"Az első tárgyalás után változott.");
  await call("reflection",replacement,{text:"Később módosított szöveg."});
  assert.equal((await call("report",b)).reflections[0],report.reflections[0]);
  await call("reportshare",host,{enabled:true});
  assert.equal((await call("report",b)).reflections[0],"Később módosított szöveg.");
  await call("reportshare",host,{enabled:false});
  await call("report",b,undefined,403);
  await call("reportshare",host,{enabled:true});
  assert.equal(early.canContinue,true);
  await call("continue",b,{index:2},403);
  const continued=await call("continue",host,{index:2});
  assert.equal(continued.phase,"open");
  assert.deepEqual(continued.rounds[2].moves,["X",null,null,null]);
  assert.deepEqual(continued.totals,early.totals);
  assert.equal((await call("",b)).reportShared,false);
  assert.equal((await call("",projector)).rounds[0].moves,undefined);
  await call("report",b,undefined,409);
  await Promise.all([b,c,d].map(key=>call("move",key,{index:2,choice:"Y"})));
  const scored=await call("close",host,{index:2});
  await call("finish",host,{index:2});
  const afterResult=await call("continue",host,{index:2});
  assert.equal(afterResult.phase,"result");
  assert.deepEqual(afterResult.totals,scored.totals);
  assert.equal((await call("next",host,{index:2})).index,3);
  for(let index=3;index<10;index++){
    await call("open",host,{index});
    await Promise.all([replacement,b,c,d].map(key=>call("move",key,{index,choice:"Y"})));
    await call("close",host,{index});
    if(index<9) await call("next",host,{index});
  }
  assert.equal((await call("finish",host,{index:9})).canContinue,false);
  await call("continue",host,{index:9},409);
  const archiveKey="a".repeat(32);
  const details={archiveKey,date:"2026-11-12",company:"Próbacég",reason:"A csapatok a végén váltottak."};
  await call("archive",b,details,403);
  const archived=await call("archive",host,details);
  assert.equal(archived.rounds,10);
  const archiveRead=(key,id="")=>xyApi(new Request("https://example.test/api/xy/archive"+id,{headers:{authorization:"Bearer "+key}}),store);
  assert.deepEqual(await (await archiveRead(archiveKey)).json(),[archived]);
  assert.equal((await archiveRead(b,"/"+archived.id)).status,404);
  const snapshot=await (await archiveRead(archiveKey,"/"+archived.id)).json();
  assert.equal(snapshot.report.rounds.length,10);
  await call("archive",host,{...details,reason:"Pontosított megjegyzés"});
  const entries=await (await archiveRead(archiveKey)).json();
  assert.equal(entries.length,1);
  assert.equal(entries[0].reason,"Pontosított megjegyzés");
  assert.equal((await activity(host)).status,403);
  const history=(await (await activity(ownerKey)).json()).entries;
  assert.equal(history.length,1);
  assert.equal(history[0].code,code);
  assert.equal(history[0].phase,"finished");
  assert.equal(history[0].round,10);
  assert.ok(history[0].updatedAt>=history[0].startedAt);
  assert.deepEqual(Object.keys(history[0]).sort(),["code","phase","round","rounds","startedAt","updatedAt"]);
});
